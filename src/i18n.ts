export const STRINGS: Record<Lang, typeof IT> = { it: IT, en: EN };

export function detectLang(): Lang {
  const l = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return l === 'it' ? 'it' : 'en';
}
